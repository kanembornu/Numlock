const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(process.env.NUMLOCK_INDEX || '190.View.Index.html', 'utf8');
const start = source.indexOf('    function ensureProductsData()');
const end = source.indexOf('    function ensureProductProfitabilityData()', start);
assert(start >= 0 && end > start);
let success, failure, calls = 0, renders = 0;
const elements = { products: { setAttribute() {} }, productsLoading: {}, productsEmpty: {}, productsError: {} };
const runner = { withSuccessHandler(fn) { success = fn; return this; }, withFailureHandler(fn) { failure = fn; return this; }, getProductCatalogReadModel() { calls++; } };
const context = { productsDataLoaded: false, productsDataLoading: false, initializeStableDashboardElements: () => elements, google: { script: { run: runner } }, console: { error() {} }, renderProductsList: () => renders++ };
vm.createContext(context);
vm.runInContext(source.slice(start, end), context);
context.ensureProductsData();
context.ensureProductsData();
assert.equal(calls, 1, 'Duplicate pending reads suppressed');
success([]);
assert.equal(renders, 1);
context.ensureProductsData();
assert.equal(calls, 1, 'Loaded catalog reused');
